import app from '../hono/hono';
import emailService from '../service/email-service';
import result from '../model/result';
import userContext from '../security/user-context';
import attService from '../service/att-service';
import r2Service from '../service/r2-service';
import { mailboxAttachment } from '../service/mailbox-attachment.mjs';

app.get('/email/list', async (c) => {
	const query = c.req.query();
	const userId = userContext.getUserId(c);
	if (query.attachmentId !== undefined) {
		return mailboxAttachment(c.env.db, key => r2Service.toObjResp(c, key, { storageHeaders: false }), userId, query);
	}
	const data = await emailService.list(c, query, userId);
	return c.json(result.ok(data));
});

app.get('/email/latest', async (c) => {
	const list = await emailService.latest(c, c.req.query(), userContext.getUserId(c));
	return c.json(result.ok(list));
});

app.delete('/email/delete', async (c) => {
	await emailService.delete(c, c.req.query(), userContext.getUserId(c));
	return c.json(result.ok());
});

app.get('/email/attList', async (c) => {
	const attList = await attService.list(c, c.req.query(), userContext.getUserId(c));
	return c.json(result.ok(attList));
});

app.post('/email/send', async (c) => {
	const email = await emailService.send(c, await c.req.json(), userContext.getUserId(c));
	return c.json(result.ok(email));
});

app.put('/email/read', async (c) => {
	await emailService.read(c, await c.req.json(), userContext.getUserId(c));
	return c.json(result.ok());
})

